"""The reverse-engineering layer's tool (re/README.md): validate, look up, generate.

  python -B tools/re_db.py check              validate every symbols file; generated files up to date
  python -B tools/re_db.py find <va|name>      matching entries in every image (sub_XXXXXXXX accepted)
  python -B tools/re_db.py list [image]        an image's entries by address (default default.xbe)
  python -B tools/re_db.py gen                 write src/re_names.c and src/re_symbols.h

Library names (XDK) are merged from the signature matcher's header and the hand pins; they are not
stored in re/symbols. The header is the game build's (build/build/default/case/inputs/xbr-symbols), or
the file FCI_SYMBOLS_HEADER names; without it, check skips comparing src/re_names.c.
"""

import json
import os
from pathlib import Path
import re
import sys

REPO = Path(__file__).resolve().parents[1]
SYMBOLS = REPO / "re" / "symbols"
SIGMATCH_HEADER = Path(
    os.environ.get(
        "FCI_SYMBOLS_HEADER",
        REPO / "build" / "build" / "default" / "case" / "inputs" / "xbr-symbols" / "image_symbols.h",
    )
)
PINS = REPO / "data" / "default.pins.json"
NAMES_C = REPO / "src" / "re_names.c"
SYMBOLS_H = REPO / "src" / "re_symbols.h"
KINDS = {"function", "global", "vtable", "string"}
CONFIDENCE = ("verified", "likely", "guess")
NAME = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
PREFIX = {"default.xbe": "GAME", "ige.xbe": "EDITOR"}


def load_images():
    out = {}
    for path in sorted(SYMBOLS.glob("*.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        out[data["image"]] = (path, data)
    return out


def library_names():
    """XDK functions the game image links, as {va: name} (signature matches and pins)."""
    names = {}
    if SIGMATCH_HEADER.exists():
        text = SIGMATCH_HEADER.read_text(encoding="utf-8")
        found = set(re.findall(r"#define HAS_(\w+) 1", text))
        for name, va in re.findall(r"#define SYM_(\w+) ([0-9A-F]{8})", text):
            if name in found:
                names[int(va, 16)] = name
    if PINS.exists():
        for name, pin in json.loads(PINS.read_text(encoding="utf-8"))["symbols"].items():
            names[int(pin["va"], 16)] = name
    return names


def problems_in(image, data):
    out = []
    seen_va, seen_name = {}, {}
    if not re.fullmatch(r"[0-9a-f]{64}", data.get("sha256", "")):
        out.append(f"{image}: sha256 missing")
    for e in data.get("symbols", []):
        where = f"{image} {e.get('va')} {e.get('name')}"
        for key in ("va", "name", "kind", "confidence", "evidence"):
            if not e.get(key):
                out.append(f"{where}: no {key}")
        if not re.fullmatch(r"0x[0-9A-F]{8}", str(e.get("va", ""))):
            out.append(f"{where}: va must be 0x + 8 upper-case hex digits")
        if e.get("kind") not in KINDS:
            out.append(f"{where}: kind must be one of {sorted(KINDS)}")
        if e.get("confidence") not in CONFIDENCE:
            out.append(f"{where}: confidence must be one of {CONFIDENCE}")
        if e.get("name") and not NAME.match(e["name"]):
            out.append(f"{where}: name is not an identifier")
        if e.get("va") in seen_va:
            out.append(f"{where}: address also named {seen_va[e['va']]}")
        if e.get("name") in seen_name:
            out.append(f"{where}: name also used at {seen_name[e['name']]}")
        seen_va[e.get("va")] = e.get("name")
        seen_name[e.get("name")] = e.get("va")
        if e.get("see") and not (SYMBOLS.parent / e["see"]).exists():
            out.append(f"{where}: see {e['see']} does not exist")
    for sname, s in data.get("structs", {}).items():
        if not NAME.match(sname):
            out.append(f"{image} struct {sname}: not an identifier")
        for key in ("confidence", "evidence"):
            if not s.get(key):
                out.append(f"{image} struct {sname}: no {key}")
        for f in s.get("fields", []):
            for key in ("offset", "name", "type", "confidence", "evidence"):
                if not f.get(key):
                    out.append(f"{image} struct {sname}.{f.get('name')}: no {key}")
    return out


def names_c(images):
    lines = [
        "/* Names for the recompiled code's diagnostics, generated by tools/re_db.py gen from re/symbols",
        " * and the XDK signature names; do not edit (re/README.md). */",
        "#include <stdint.h>",
        "#include <string.h>",
        "",
        '#include "fci_image.h"',
        "",
        "typedef struct { uint32_t va; const char *name; } re_name;",
        "",
    ]
    for image, (_, data) in images.items():
        entries = {int(e["va"], 16): e["name"] for e in data["symbols"]}
        if image == "default.xbe":
            for va, name in library_names().items():
                entries.setdefault(va, name)
        ident = PREFIX.get(image, re.sub(r"\W", "_", image)).lower()
        lines.append(f"static const re_name re_names_{ident}[] = {{")
        lines += [f'    {{0x{va:08X}u, "{name}"}},' for va, name in sorted(entries.items())]
        lines += ["    {0u, 0}", "};", ""]
    lines += [
        "/* the name of a guest address in the image compiled into this process, or 0 */",
        "const char *fci_re_name(uint32_t va)",
        "{",
        "    const re_name *t;",
        "    size_t lo = 0, hi, mid;",
    ]
    for image in images:
        ident = PREFIX.get(image, re.sub(r"\W", "_", image)).lower()
        lines.append(f'    if (!strcmp(FCI_IMAGE_FILENAME, "{image}")) t = re_names_{ident}; else')
    lines += [
        "        return 0;",
        "    for (hi = 0; t[hi].name; hi++)",
        "        ;",
        "    while (lo < hi) {",
        "        mid = (lo + hi) / 2;",
        "        if (t[mid].va == va) return t[mid].name;",
        "        if (t[mid].va < va) lo = mid + 1; else hi = mid;",
        "    }",
        "    return 0;",
        "}",
        "",
    ]
    return "\n".join(lines)


def symbols_h(images):
    lines = [
        "/* Named original addresses for host code (hooks, input), generated by tools/re_db.py gen from",
        " * re/symbols (verified and likely entries); do not edit (re/README.md). */",
        "#pragma once",
        "",
    ]
    for image, (_, data) in images.items():
        prefix = PREFIX.get(image, re.sub(r"\W", "_", image).upper())
        lines.append(f"/* {image} */")
        for e in sorted(data["symbols"], key=lambda e: e["va"]):
            if e["confidence"] in ("verified", "likely"):
                define = f"#define RE_{prefix}_{e['name'].upper()} {e['va']}u"
                lines.append(f"{define}  /* {e['kind']}, {e['confidence']} */")
        for sname, s in sorted(data.get("structs", {}).items()):
            for f in s.get("fields", []):
                if f["offset"].startswith("0x") and f["confidence"] in ("verified", "likely"):
                    lines.append(
                        f"#define RE_{prefix}_{sname.upper()}_{f['name'].upper()} {f['offset']}u  /* {f['type']} */"
                    )
        lines.append("")
    return "\n".join(lines)


def find(images, key):
    want_va = None
    k = key[4:] if key.lower().startswith("sub_") else key
    if re.fullmatch(r"(0x)?[0-9A-Fa-f]{1,8}", k):
        want_va = int(k, 16)
    found = 0
    for image, (_, data) in images.items():
        for e in data["symbols"]:
            if (want_va is not None and int(e["va"], 16) == want_va) or e["name"].lower() == key.lower():
                print(f"{image} {e['va']} {e['name']} ({e['kind']}, {e['confidence']})\n  {e['evidence']}")
                if e.get("notes"):
                    print(f"  notes: {e['notes']}")
                found += 1
    if want_va is not None:
        lib = library_names().get(want_va)
        if lib:
            print(f"default.xbe 0x{want_va:08X} {lib} (library, signature)")
            found += 1
    if not found:
        print("not named")


def main(argv):
    images = load_images()
    cmd = argv[0] if argv else "check"
    if cmd == "check":
        probs = [p for image, (_, data) in images.items() for p in problems_in(image, data)]
        if not SIGMATCH_HEADER.exists():
            print(f"no {SIGMATCH_HEADER}: src/re_names.c not compared (build the game first)")
        elif NAMES_C.read_text(encoding="utf-8") != names_c(images) if NAMES_C.exists() else True:
            probs.append("src/re_names.c is out of date: run tools/re_db.py gen")
        if SYMBOLS_H.read_text(encoding="utf-8") != symbols_h(images) if SYMBOLS_H.exists() else True:
            probs.append("src/re_symbols.h is out of date: run tools/re_db.py gen")
        for p in probs:
            print(p)
        n = sum(len(d["symbols"]) for _, d in images.values())
        print(
            f"{len(images)} images, {n} names, {len(library_names())} library names: "
            f"{'ok' if not probs else str(len(probs)) + ' problem(s)'}"
        )
        return 1 if probs else 0
    if cmd == "gen":
        if not SIGMATCH_HEADER.exists():
            raise SystemExit(f"error: {SIGMATCH_HEADER} is missing; build the game first")
        NAMES_C.write_text(names_c(images), encoding="utf-8", newline="\n")
        SYMBOLS_H.write_text(symbols_h(images), encoding="utf-8", newline="\n")
        print(f"wrote {NAMES_C.relative_to(REPO)} and {SYMBOLS_H.relative_to(REPO)}")
        return 0
    if cmd == "find" and len(argv) > 1:
        find(images, argv[1])
        return 0
    if cmd == "list":
        image = argv[1] if len(argv) > 1 else "default.xbe"
        for e in sorted(images[image][1]["symbols"], key=lambda e: e["va"]):
            print(f"{e['va']} {e['confidence']:8} {e['kind']:8} {e['name']}")
        return 0
    raise SystemExit(__doc__)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
